import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { JsonRpcProvider, Contract, ZeroAddress } from 'ethers';
const record=JSON.parse(await readFile('deployments/botchain-testnet.json','utf8'));
const artifact=JSON.parse(await readFile('artifacts/LuckyProof.json','utf8'));
const provider=new JsonRpcProvider(record.rpcUrl);
assert.equal((await provider.getNetwork()).chainId,968n);
const contract=new Contract(record.address,artifact.abi,provider);
const receipt=await provider.getTransactionReceipt(record.transactionHash);
assert.equal(receipt.status,1);assert.equal(receipt.contractAddress.toLowerCase(),record.address.toLowerCase());
assert.equal(await contract.providerAdministrator(),record.deployer);
assert.equal(await contract.provider(),record.randomnessProvider);
assert.ok((await provider.getCode(record.address)).length>100);
const count=await contract.drawCount();
const block=await provider.getBlock('latest');
const unsigned={from:record.deployer,to:record.address,data:contract.interface.encodeFunctionData('createDraw',['Read-only deployment check',block.timestamp+86400])};
const call=await provider.call(unsigned);
assert.equal(contract.interface.decodeFunctionResult('createDraw',call)[0],count+1n);
if(record.randomnessProvider===ZeroAddress) await assert.rejects(contract.selectWinner.staticCall(1),/Randomness provider not configured/);
await assert.rejects(contract.register.staticCall(0),/Registration closed/);
await assert.rejects(contract.configureProvider.staticCall(ZeroAddress),/Administrator only/);
console.log('PASS: deployment receipt, live code, administrator, provider, draw creation call, and disabled invalid actions. No test transactions sent.');
console.log(JSON.stringify({address:record.address,drawCount:count.toString(),randomnessConfigured:record.randomnessProvider!==ZeroAddress,block:receipt.blockNumber}));
